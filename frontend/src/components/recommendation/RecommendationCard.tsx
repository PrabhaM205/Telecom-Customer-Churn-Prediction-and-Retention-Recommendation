// frontend/src/components/recommendation/RecommendationCard.tsx

import { Download } from "lucide-react";
import { jsPDF } from "jspdf";
import PriorityBadge from "./PriorityBadge";
import type { Recommendation } from "@/api/types";
import { toast } from "sonner";

interface RecommendationCardProps {
  recommendation: Recommendation;
  onAccept: (id: string) => void;
  onDismiss: (id: string) => void;
  isUpdating?: boolean;
}

function formatCurrency(value: number | null): string {
  return value == null
    ? "—"
    : `$${value.toLocaleString(undefined, {
        maximumFractionDigits: 0,
      })}`;
}

export default function RecommendationCard({
  recommendation,
  onAccept,
  onDismiss,
  isUpdating,
}: RecommendationCardProps) {
  const {
    customer_id,
    title,
    description,
    priority_score,
    expected_revenue_impact,
    status,
  } = recommendation;

  // Download recommendation as PDF
  const handleDownloadPDF = () => {
    try {
      const pdf = new jsPDF();

      const margin = 20;
      const pageWidth = pdf.internal.pageSize.getWidth();

      // Header
      pdf.setFontSize(20);
      pdf.setFont("helvetica", "bold");
      pdf.text("Customer Retention Offer", margin, 25);

      // Divider
      pdf.setDrawColor(200, 200, 200);
      pdf.line(margin, 32, pageWidth - margin, 32);

      // Customer ID
      pdf.setFontSize(11);
      pdf.setFont("helvetica", "bold");
      pdf.text("Customer ID", margin, 45);

      pdf.setFont("helvetica", "normal");
      pdf.text(customer_id, margin, 52);

      // Offer title
      pdf.setFont("helvetica", "bold");
      pdf.text("Offer", margin, 67);

      pdf.setFont("helvetica", "normal");

      const titleLines = pdf.splitTextToSize(
        title,
        pageWidth - margin * 2
      );

      pdf.text(titleLines, margin, 74);

      // Description
      const descriptionStartY = 74 + titleLines.length * 7 + 10;

      pdf.setFont("helvetica", "bold");
      pdf.text("Description", margin, descriptionStartY);

      pdf.setFont("helvetica", "normal");

      const descriptionLines = pdf.splitTextToSize(
        description,
        pageWidth - margin * 2
      );

      pdf.text(
        descriptionLines,
        margin,
        descriptionStartY + 8
      );

      // Priority
      const priorityY =
        descriptionStartY +
        8 +
        descriptionLines.length * 6 +
        15;

      pdf.setFont("helvetica", "bold");
      pdf.text("Priority Score", margin, priorityY);

      pdf.setFont("helvetica", "normal");
      pdf.text(
        priority_score.toFixed(2),
        margin,
        priorityY + 8
      );

      // Revenue impact
      pdf.setFont("helvetica", "bold");
      pdf.text(
        "Expected Revenue Impact",
        margin,
        priorityY + 25
      );

      pdf.setFont("helvetica", "normal");
      pdf.text(
        formatCurrency(expected_revenue_impact),
        margin,
        priorityY + 33
      );

      // Status
      pdf.setFont("helvetica", "bold");
      pdf.text("Status", margin, priorityY + 50);

      pdf.setFont("helvetica", "normal");
      pdf.text(status, margin, priorityY + 58);

      // Footer
      pdf.setFontSize(9);
      pdf.setTextColor(120, 120, 120);

      pdf.text(
        "Generated by Telecom Customer Retention System",
        margin,
        pdf.internal.pageSize.getHeight() - 15
      );

      // Download
      const fileName = `retention-offer-${customer_id}.pdf`;

      pdf.save(fileName);

      toast.success("Offer downloaded successfully", {
        description: `PDF downloaded for customer ${customer_id}.`,
      });
    } catch (error) {
      console.error("PDF generation failed:", error);

      toast.error("Failed to download offer", {
        description: "Unable to generate the PDF.",
      });
    }
  };

  // Accept offer
  const handleAccept = () => {
    onAccept(recommendation.id);

    toast.success("Offer has been sent through email", {
      description: `Retention offer sent to customer ${customer_id}.`,
      duration: 4000,
    });
  };

  return (
    <div className="rounded-lg border border-gray-200 bg-white p-5">
      {/* Header */}
      <div className="flex items-start justify-between gap-4">
        <div>
          <div className="text-xs text-gray-400">
            {customer_id}
          </div>

          <div className="mt-0.5 text-sm font-semibold text-gray-900">
            {title}
          </div>
        </div>

        {/* Priority + Download */}
        <div className="flex items-center gap-2">
          <PriorityBadge priorityScore={priority_score} />

          <button
            type="button"
            onClick={handleDownloadPDF}
            title="Download offer as PDF"
            className="flex h-8 w-8 items-center justify-center rounded-md border border-gray-200 text-gray-500 transition hover:bg-gray-50 hover:text-gray-900"
          >
            <Download size={16} />
          </button>
        </div>
      </div>

      {/* Description */}
      <p className="mt-2 text-sm text-gray-600">
        {description}
      </p>

      {/* Revenue Impact */}
      <div className="mt-3 text-xs text-gray-500">
        Est. revenue impact:{" "}
        {formatCurrency(expected_revenue_impact)}
      </div>

      {/* Actions */}
      {status === "pending" ? (
        <div className="mt-4 flex gap-2">
          {/* Accept */}
          <button
            onClick={handleAccept}
            disabled={isUpdating}
            className="rounded-md bg-gray-900 px-3 py-1.5 text-xs font-medium text-white hover:bg-gray-700 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {isUpdating ? "Sending..." : "Accept"}
          </button>

          {/* Dismiss */}
          <button
            onClick={() => onDismiss(recommendation.id)}
            disabled={isUpdating}
            className="rounded-md border border-gray-200 px-3 py-1.5 text-xs font-medium text-gray-600 hover:bg-gray-50 disabled:cursor-not-allowed disabled:opacity-50"
          >
            Dismiss
          </button>
        </div>
      ) : (
        <div className="mt-4 text-xs font-medium text-gray-400">
          {status === "accepted" ? "Accepted" : "Dismissed"}
        </div>
      )}
    </div>
  );
}